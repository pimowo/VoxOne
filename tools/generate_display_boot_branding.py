#!/usr/bin/env python3
"""Generate compact firmware boot-logo data from the official branding kit."""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DISPLAY_ASSETS = ROOT / "assets" / "branding" / "display"
OUTPUT_DIR = ROOT / "src" / "displays" / "fonts"

SOURCES = {
    "oled": (
        DISPLAY_ASSETS / "boot-oled-128x64-rowmajor-msb.bin",
        "e13fc35b86d0c9c05372723343b9b105f0e2311d368a28057b71432dfb608773",
    ),
    "st7789": (
        DISPLAY_ASSETS / "boot-st7789-284x76-RGB565-LE.bin",
        "7059b8b7f5fa4d7186f03c076268422dc1cb9491c3a2a54cf4b8cbf1dac2c6b9",
    ),
    "st7796": (
        DISPLAY_ASSETS / "boot-st7796-480x320-RGB565-LE.bin",
        "bd061415eea99cb7be549183cf212b5620e721b706d8a17e4c0427beaed27700",
    ),
}


def read_verified(name: str) -> bytes:
    path, expected_sha256 = SOURCES[name]
    data = path.read_bytes()
    actual = hashlib.sha256(data).hexdigest()
    if actual != expected_sha256:
        raise ValueError(f"official asset changed: {path} ({actual})")
    return data


def format_bytes(data: bytes) -> str:
    lines = []
    for start in range(0, len(data), 16):
        chunk = data[start : start + 16]
        lines.append("  " + ", ".join(f"0x{value:02X}" for value in chunk) + ",")
    return "\n".join(lines)


def header_prelude(source_name: str, variant_namespace: str) -> str:
    return f"""// Generated by tools/generate_display_boot_branding.py.
// Source: assets/branding/display/{source_name}
// Do not edit by hand; regenerate from the official branding asset.
#pragma once

#include <stddef.h>
#include <stdint.h>

#ifndef PROGMEM
#define PROGMEM
#endif

namespace voxone {{
namespace display_boot_branding {{
namespace {variant_namespace} {{
"""


def oled_header() -> str:
    source = read_verified("oled")
    if len(source) != 128 * 64 // 8:
        raise ValueError("unexpected OLED source length")

    left, source_top, width, height, target_top = 10, 20, 108, 23, 5
    stride = 128 // 8
    packed_stride = (width + 7) // 8
    cropped = bytearray(packed_stride * height)
    for y in range(height):
        for x in range(width):
            source_x = left + x
            source_byte = source[(source_top + y) * stride + source_x // 8]
            if source_byte & (0x80 >> (source_x % 8)):
                cropped[y * packed_stride + x // 8] |= 0x80 >> (x % 8)

    return (
        header_prelude("boot-oled-128x64-rowmajor-msb.bin", "oled")
        + f"""
constexpr uint16_t kBootLogoWidth = {width};
constexpr uint16_t kBootLogoHeight = {height};
constexpr int16_t kBootLogoLeft = {left};
constexpr int16_t kBootLogoTop = {target_top};
constexpr uint16_t kBootLogoRowBytes = {packed_stride};
static const uint8_t kBootLogoBitmap[{len(cropped)}] PROGMEM = {{
{format_bytes(bytes(cropped))}
}};
static_assert(sizeof(kBootLogoBitmap) == kBootLogoRowBytes * kBootLogoHeight,
              "OLED boot logo bitmap length mismatch");

}}  // namespace oled
}}  // namespace display_boot_branding
}}  // namespace voxone
"""
    )


def encode_rle565_rows(data: bytes, width: int, height: int,
                       crop: tuple[int, int, int, int]) -> bytes:
    if len(data) != width * height * 2:
        raise ValueError("unexpected RGB565 source length")
    pixels = [data[i] | (data[i + 1] << 8) for i in range(0, len(data), 2)]
    left, top, crop_width, crop_height = crop
    encoded = bytearray()
    for y in range(top, top + crop_height):
        row = pixels[y * width + left : y * width + left + crop_width]
        x = 0
        while x < crop_width:
            color = row[x]
            end = x + 1
            while end < crop_width and row[end] == color:
                end += 1
            run = end - x
            value = run
            while value >= 0x80:
                encoded.append((value & 0x7F) | 0x80)
                value >>= 7
            encoded.append(value)
            encoded.extend((color & 0xFF, color >> 8))
            x = end
    return bytes(encoded)


def tft_header(name: str, source_name: str, source_width: int,
               source_height: int, crop: tuple[int, int, int, int],
               target_top: int) -> str:
    source = read_verified(name)
    encoded = encode_rle565_rows(source, source_width, source_height, crop)
    left, _source_top, width, height = crop
    return (
        header_prelude(source_name, name)
        + f"""
constexpr uint16_t kBootLogoWidth = {width};
constexpr uint16_t kBootLogoHeight = {height};
constexpr int16_t kBootLogoLeft = {left};
constexpr int16_t kBootLogoTop = {target_top};
constexpr uint32_t kBootLogoPixelCount =
    static_cast<uint32_t>(kBootLogoWidth) * kBootLogoHeight;
static const uint8_t kBootLogoRle565[{len(encoded)}] PROGMEM = {{
{format_bytes(encoded)}
}};
constexpr size_t kBootLogoRle565Size = sizeof(kBootLogoRle565);

}}  // namespace {name}
}}  // namespace display_boot_branding
}}  // namespace voxone
"""
    )


def generated_files() -> dict[Path, str]:
    return {
        OUTPUT_DIR / "voxone_boot_logo_oled_128x64.h": oled_header(),
        OUTPUT_DIR / "voxone_boot_logo_st7789_284x76.h": tft_header(
            "st7789", "boot-st7789-284x76-RGB565-LE.bin", 284, 76,
            (53, 18, 178, 40), 4),
        OUTPUT_DIR / "voxone_boot_logo_st7796_480x320.h": tft_header(
            "st7796", "boot-st7796-480x320-RGB565-LE.bin", 480, 320,
            (36, 115, 408, 89), 115),
    }


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true",
                        help="fail if committed headers do not match the kit")
    args = parser.parse_args()
    files = generated_files()
    if args.check:
        stale = [str(path.relative_to(ROOT)) for path, expected in files.items()
                 if not path.exists() or path.read_text(encoding="utf-8") != expected]
        if stale:
            raise SystemExit("stale display boot branding: " + ", ".join(stale))
        print("display boot branding assets: PASS")
        return 0
    for path, contents in files.items():
        path.write_text(contents, encoding="utf-8")
        print(path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
